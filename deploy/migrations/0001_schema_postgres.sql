-- Sesiones Punto Cero — esquema para PostgreSQL (Render)
-- Equivalente al esquema SQLite del tablero (drizzle/0001–0005).
-- Ejecutar una sola vez sobre la base nueva, antes de 0002_seed.sql.

CREATE TABLE IF NOT EXISTS sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name text NOT NULL,
  status text NOT NULL DEFAULT 'pendiente'
    CHECK (status IN ('pendiente', 'en_edicion', 'entregada', 'no_show')),
  session_date date,
  delivery_date date,
  delivery_date_estimated boolean NOT NULL DEFAULT false,
  delivery_type text CHECK (delivery_type IS NULL OR delivery_type IN ('ESTANDAR', 'EXPRESS')),
  package_label text,
  photo_count integer,
  favorites_chosen boolean NOT NULL DEFAULT false,
  favorites_count integer,
  drive_url text,
  uploaded_at date,
  sent boolean NOT NULL DEFAULT false,
  charges_settled boolean NOT NULL DEFAULT false,
  unpaid boolean NOT NULL DEFAULT false,
  face_level text,
  body_adjustments text,
  publish_permission text CHECK (publish_permission IS NULL OR publish_permission IN ('SI', 'NO')),
  motive text,
  do_not_touch text,
  background_color text,
  first_session boolean,
  discovery_source text,
  notes text,
  delivered_at date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sessions_delivery_date_idx ON sessions (delivery_date);
CREATE INDEX IF NOT EXISTS sessions_session_date_idx ON sessions (session_date);

CREATE TABLE IF NOT EXISTS expenses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month text NOT NULL,
  expense_date date,
  kind text NOT NULL CHECK (kind IN ('fijo', 'variable')),
  description text NOT NULL,
  amount integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS expenses_month_idx ON expenses (month);

CREATE TABLE IF NOT EXISTS monthly_closes (
  month text PRIMARY KEY,
  estimate_sales integer,
  projected_sales integer,
  actual_sales integer,
  actual_fixed_costs integer,
  actual_variable_costs integer,
  notes text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
